export function annualMessageForDate(date: string): DailyMessage {
  const [year,month,day]=date.split("-").map(Number);
  const start=Date.UTC(year,0,1);
  const index=Math.floor((Date.UTC(year,month-1,day)-start)/86400000);
  // No dia 29/02 usa a mensagem do dia anterior, sem deslocar as datas restantes.
  const normalized=(year%4===0&&(year%100!==0||year%400===0)&&index>=59)?index-1:index;
  return annualMessages[Math.max(0,Math.min(364,normalized))];
}
